-- KayuUkur Pro · Supabase PostgreSQL schema
-- Public catalogue is read-only. All writes are protected by RLS and app_metadata.role = 'admin'.
begin;

create extension if not exists pgcrypto;

create or replace function public.is_kayu_admin()
returns boolean
language sql stable
as $$
  select coalesce(auth.jwt() -> 'app_metadata' ->> 'role', '') = 'admin'
      or coalesce(auth.jwt() -> 'app_metadata' -> 'roles', '[]'::jsonb) @> '["admin"]'::jsonb;
$$;

create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin new.updated_at = now(); return new; end;
$$;

create table if not exists public.categories (
  id text primary key,
  slug text not null unique,
  name text not null,
  description text not null default '',
  image_key text not null default 'hand-tools',
  is_published boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  category_id text not null references public.categories(id) on update cascade on delete restrict,
  name text not null,
  subcategory text not null default '',
  code text not null,
  image_key text not null default 'hand-tools',
  description text not null default '',
  uses text not null default '',
  note text not null default '',
  verification text not null default 'example' check (verification in ('example','mathematical','verified')),
  aliases text[] not null default '{}',
  specifications jsonb not null default '{}'::jsonb,
  is_published boolean not null default true,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists products_category_idx on public.products(category_id);
create index if not exists products_slug_idx on public.products(slug);
create index if not exists products_aliases_idx on public.products using gin(aliases);
create index if not exists products_search_idx on public.products using gin (
  to_tsvector('simple', coalesce(name,'') || ' ' || coalesce(code,'') || ' ' || coalesce(subcategory,'') || ' ' || coalesce(description,''))
);

create table if not exists public.product_images (
  id uuid primary key default gen_random_uuid(),
  product_id uuid not null references public.products(id) on delete cascade,
  url text not null,
  alt_text text not null default '',
  sort_order integer not null default 0,
  is_primary boolean not null default false,
  created_at timestamptz not null default now()
);
create index if not exists product_images_product_idx on public.product_images(product_id, sort_order);

create table if not exists public.product_specifications (
  id uuid primary key default gen_random_uuid(),
  product_id uuid not null references public.products(id) on delete cascade,
  key text not null,
  value text not null,
  unit text not null default '',
  verified boolean not null default false,
  source_note text not null default '',
  created_at timestamptz not null default now(),
  unique(product_id, key)
);

create table if not exists public.aliases (
  id uuid primary key default gen_random_uuid(),
  alias text not null,
  product_id uuid references public.products(id) on delete cascade,
  category_id text references public.categories(id) on delete cascade,
  created_at timestamptz not null default now(),
  check (product_id is not null or category_id is not null)
);
create index if not exists aliases_search_idx on public.aliases using gin(to_tsvector('simple', alias));

create table if not exists public.unit_conversions (
  id bigint generated by default as identity primary key,
  from_unit text not null,
  to_unit text not null,
  factor numeric not null,
  exact boolean not null default true,
  note text not null default '',
  unique(from_unit, to_unit)
);

create table if not exists public.learning_modules (
  slug text primary key check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  title text not null,
  category text not null default 'Dasar',
  minutes integer not null default 5 check (minutes between 1 and 180),
  image_key text not null default 'measuring-tools',
  intro text not null default '',
  body jsonb not null default '[]'::jsonb,
  takeaway text not null default '',
  question jsonb not null default '{}'::jsonb,
  is_published boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists learning_modules_category_idx on public.learning_modules(category);

create table if not exists public.quizzes (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique,
  title text not null,
  description text not null default '',
  is_published boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.quiz_questions (
  id uuid primary key default gen_random_uuid(),
  quiz_id uuid references public.quizzes(id) on delete cascade,
  category text not null default 'umum',
  prompt text not null,
  options jsonb not null default '[]'::jsonb,
  answer text not null,
  explanation text not null default '',
  image_key text,
  is_published boolean not null default true,
  created_at timestamptz not null default now(),
  check (jsonb_typeof(options) = 'array')
);
create index if not exists quiz_questions_quiz_idx on public.quiz_questions(quiz_id, category);

create table if not exists public.achievements (
  id text primary key,
  title text not null,
  description text not null default '',
  icon text not null default 'star',
  xp_reward integer not null default 0 check (xp_reward >= 0)
);

create table if not exists public.user_progress (
  user_id uuid primary key references auth.users(id) on delete cascade,
  xp integer not null default 0 check (xp >= 0),
  answered integer not null default 0 check (answered >= 0),
  correct integer not null default 0 check (correct between 0 and answered),
  streak integer not null default 0 check (streak >= 0),
  best_streak integer not null default 0 check (best_streak >= streak),
  last_study_date date,
  wrong_question_ids text[] not null default '{}',
  completed_learning text[] not null default '{}',
  earned_badges text[] not null default '{}',
  category_stats jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

create table if not exists public.favorites (
  user_id uuid not null references auth.users(id) on delete cascade,
  product_id uuid not null references public.products(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key(user_id, product_id)
);

create table if not exists public.conversion_history (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  input_text text not null,
  from_unit text not null,
  to_unit text not null,
  exact_value numeric not null,
  exact_result numeric not null,
  created_at timestamptz not null default now()
);
create index if not exists conversion_history_user_created_idx on public.conversion_history(user_id, created_at desc);

create table if not exists public.user_preferences (
  user_id uuid primary key references auth.users(id) on delete cascade,
  preferences jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

create trigger categories_updated_at before update on public.categories for each row execute procedure public.set_updated_at();
create trigger products_updated_at before update on public.products for each row execute procedure public.set_updated_at();
create trigger learning_modules_updated_at before update on public.learning_modules for each row execute procedure public.set_updated_at();
create trigger user_progress_updated_at before update on public.user_progress for each row execute procedure public.set_updated_at();
create trigger user_preferences_updated_at before update on public.user_preferences for each row execute procedure public.set_updated_at();

alter table public.categories enable row level security;
alter table public.products enable row level security;
alter table public.product_images enable row level security;
alter table public.product_specifications enable row level security;
alter table public.aliases enable row level security;
alter table public.unit_conversions enable row level security;
alter table public.learning_modules enable row level security;
alter table public.quizzes enable row level security;
alter table public.quiz_questions enable row level security;
alter table public.achievements enable row level security;
alter table public.user_progress enable row level security;
alter table public.favorites enable row level security;
alter table public.conversion_history enable row level security;
alter table public.user_preferences enable row level security;

-- Catalogue/reference is readable to anon/authenticated, but only admins can change it.
create policy "published categories readable" on public.categories for select using (is_published = true or public.is_kayu_admin());
create policy "admin manages categories" on public.categories for all to authenticated using (public.is_kayu_admin()) with check (public.is_kayu_admin());
create policy "published products readable" on public.products for select using (is_published = true or public.is_kayu_admin());
create policy "admin manages products" on public.products for all to authenticated using (public.is_kayu_admin()) with check (public.is_kayu_admin());
create policy "published product images readable" on public.product_images for select using (exists(select 1 from public.products p where p.id = product_id and p.is_published = true) or public.is_kayu_admin());
create policy "admin manages product images" on public.product_images for all to authenticated using (public.is_kayu_admin()) with check (public.is_kayu_admin());
create policy "published specifications readable" on public.product_specifications for select using (exists(select 1 from public.products p where p.id = product_id and p.is_published = true) or public.is_kayu_admin());
create policy "admin manages specifications" on public.product_specifications for all to authenticated using (public.is_kayu_admin()) with check (public.is_kayu_admin());
create policy "aliases readable" on public.aliases for select using (true);
create policy "admin manages aliases" on public.aliases for all to authenticated using (public.is_kayu_admin()) with check (public.is_kayu_admin());
create policy "unit conversions readable" on public.unit_conversions for select using (true);
create policy "admin manages unit conversions" on public.unit_conversions for all to authenticated using (public.is_kayu_admin()) with check (public.is_kayu_admin());
create policy "published modules readable" on public.learning_modules for select using (is_published = true or public.is_kayu_admin());
create policy "admin manages modules" on public.learning_modules for all to authenticated using (public.is_kayu_admin()) with check (public.is_kayu_admin());
create policy "published quizzes readable" on public.quizzes for select using (is_published = true or public.is_kayu_admin());
create policy "admin manages quizzes" on public.quizzes for all to authenticated using (public.is_kayu_admin()) with check (public.is_kayu_admin());
create policy "published questions readable" on public.quiz_questions for select using (is_published = true or public.is_kayu_admin());
create policy "admin manages questions" on public.quiz_questions for all to authenticated using (public.is_kayu_admin()) with check (public.is_kayu_admin());
create policy "achievements readable" on public.achievements for select using (true);
create policy "admin manages achievements" on public.achievements for all to authenticated using (public.is_kayu_admin()) with check (public.is_kayu_admin());

-- Personal data is visible/writable only by the matching authenticated user.
create policy "own progress select" on public.user_progress for select to authenticated using (auth.uid() = user_id);
create policy "own progress insert" on public.user_progress for insert to authenticated with check (auth.uid() = user_id);
create policy "own progress update" on public.user_progress for update to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "own favorites all" on public.favorites for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "own history all" on public.conversion_history for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "own preferences all" on public.user_preferences for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);

grant select on public.categories, public.products, public.product_images, public.product_specifications, public.aliases, public.unit_conversions, public.learning_modules, public.quizzes, public.quiz_questions, public.achievements to anon, authenticated;
grant insert, update, delete on public.categories, public.products, public.product_images, public.product_specifications, public.aliases, public.unit_conversions, public.learning_modules, public.quizzes, public.quiz_questions, public.achievements to authenticated;
grant select, insert, update, delete on public.user_progress, public.favorites, public.conversion_history, public.user_preferences to authenticated;

-- Optional public read / admin-only write policy for Storage product-images.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('product-images', 'product-images', true, 5242880, array['image/jpeg','image/png','image/webp'])
on conflict (id) do nothing;
create policy "public product image read" on storage.objects for select using (bucket_id = 'product-images');
create policy "admin uploads product image" on storage.objects for insert to authenticated with check (bucket_id = 'product-images' and public.is_kayu_admin());
create policy "admin updates product image" on storage.objects for update to authenticated using (bucket_id = 'product-images' and public.is_kayu_admin()) with check (bucket_id = 'product-images' and public.is_kayu_admin());
create policy "admin deletes product image" on storage.objects for delete to authenticated using (bucket_id = 'product-images' and public.is_kayu_admin());

commit;
